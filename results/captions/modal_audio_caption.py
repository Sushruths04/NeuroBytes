"""Audio (CLAP) and caption (Qwen2.5-VL -> MPNet) features on Modal for the X3 streams (17 Oct 2026, user-approved Modal use).

    modal run scripts/modal_audio_caption.py --limit 4     # smoke test, nothing saved
    modal run scripts/modal_audio_caption.py               # all 1102 official clips
Outputs (../outputs/mindread_features/):
    clap_audio.npz     ids, feats (N, 512)  CLAP audio projection; silent clips get the embedding of silence
    caption_mpnet.npz  ids, feats (N, 768)  MPNet embedding of one generated caption per clip
    captions.json      {id: caption}
Captions are generated by our own model from the official mp4s. No EMD captions are read.
The volume `mindread-videos` is deleted at the end; verify with `modal volume list` and `modal app list`.
"""
import glob, io, json, os

import modal

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..', 'data', 'challenge_official', 'eeg-mind-reading-challenge'))
OUT = os.path.normpath(os.path.join(HERE, '..', '..', 'outputs', 'mindread_features'))
CLAP = 'laion/larger_clap_general'
VLM = 'Qwen/Qwen2.5-VL-3B-Instruct'
TXT = 'sentence-transformers/all-mpnet-base-v2'
PROMPT = ('Describe this 3-second video clip in one sentence: the scene, the main people or objects, '
          'and what they are doing.')

app = modal.App('mindread-audio-caption')
vol = modal.Volume.from_name('mindread-videos', create_if_missing=True)
image = (modal.Image.debian_slim(python_version='3.11')
         .pip_install('torch==2.6.0', 'torchvision==0.21.0', 'transformers==4.53.2', 'accelerate==1.8.1',
                      'sentence-transformers==4.1.0', 'av==13.1.0', 'numpy<2.1', 'pillow'))


@app.function(image=image, gpu='L4', volumes={'/videos': vol}, timeout=3600)
def extract(limit: int = 0):
    import av, numpy as np, torch
    from huggingface_hub import HfApi
    from PIL import Image
    from sentence_transformers import SentenceTransformer
    from transformers import AutoProcessor, ClapModel, ClapProcessor, Qwen2_5_VLForConditionalGeneration

    revs = {m: HfApi().model_info(m).sha for m in (CLAP, VLM, TXT)}
    print('revisions', revs, flush=True)
    paths = sorted(glob.glob('/videos/*.mp4'))
    if limit:
        paths = paths[:limit]

    def read(p):
        c = av.open(p, metadata_errors='ignore')
        frames = [f.to_image() for f in c.decode(video=0)]
        c.close()
        c = av.open(p, metadata_errors='ignore'); audio = None
        if c.streams.audio:
            rs = av.AudioResampler(format='flt', layout='mono', rate=48000)
            chunks = [r.to_ndarray().reshape(-1) for fr in c.decode(audio=0) for r in rs.resample(fr)]
            chunks += [r.to_ndarray().reshape(-1) for r in rs.resample(None)]
            audio = np.concatenate(chunks).astype(np.float32) if chunks else None
        c.close()
        return frames, audio

    cp = ClapProcessor.from_pretrained(CLAP, revision=revs[CLAP])
    cm = ClapModel.from_pretrained(CLAP, revision=revs[CLAP]).eval().cuda()
    vp = AutoProcessor.from_pretrained(VLM, revision=revs[VLM])
    vm = Qwen2_5_VLForConditionalGeneration.from_pretrained(VLM, revision=revs[VLM], torch_dtype=torch.bfloat16).eval().cuda()
    chat = vp.apply_chat_template([{'role': 'user', 'content': [{'type': 'video'}, {'type': 'text', 'text': PROMPT}]}],
                                  add_generation_prompt=True)
    ids, clap, caps = [], [], {}
    for i, p in enumerate(paths):
        vid = int(os.path.basename(p).split('.')[0])
        frames, audio = read(p)
        a = audio if audio is not None and len(audio) else np.zeros(48000 * 3, np.float32)
        x = cp(audios=[a], sampling_rate=48000, return_tensors='pt').to('cuda')
        with torch.no_grad():
            clap.append(cm.get_audio_features(**x)[0].float().cpu().numpy())
        pick = np.linspace(0, len(frames) - 1, 8).astype(int)
        clip = [frames[j].resize((448, int(448 * frames[j].height / frames[j].width) // 28 * 28 or 252)) for j in pick]
        inp = vp(text=[chat], videos=[clip], return_tensors='pt').to('cuda')
        with torch.no_grad():
            out = vm.generate(**inp, max_new_tokens=48, do_sample=False)
        caps[vid] = vp.batch_decode(out[:, inp['input_ids'].shape[1]:], skip_special_tokens=True)[0].strip()
        ids.append(vid)
        if i % 50 == 0 or limit:
            print(i, vid, 'audio' if audio is not None else 'silent', '|', caps[vid], flush=True)
    del vm, cm; torch.cuda.empty_cache()
    st = SentenceTransformer(TXT, revision=revs[TXT], device='cuda')
    txt = st.encode([caps[v] for v in ids], normalize_embeddings=False)
    res = {}
    for name, F, model in (('clap_audio', np.stack(clap), CLAP), ('caption_mpnet', np.asarray(txt), f'{VLM} -> {TXT}')):
        buf = io.BytesIO()
        np.savez(buf, ids=np.array(ids), feats=F.astype(np.float32), model=model,
                 revision=json.dumps(revs) + '; 8 frames; prompt: ' + PROMPT)
        res[name] = buf.getvalue()
    res['captions'] = json.dumps({str(k): v for k, v in caps.items()}, indent=1).encode()
    return res


@app.local_entrypoint()
def main(limit: int = 0):
    paths = sorted(glob.glob(os.path.join(ROOT, 'stimuli_train', '*.mp4')) + glob.glob(os.path.join(ROOT, 'stimuli_test', '*.mp4')))
    print('uploading', len(paths), 'clips')
    with vol.batch_upload(force=True) as b:
        for p in paths:
            b.put_file(p, '/' + os.path.basename(p))
    try:
        res = extract.remote(limit)
        if limit:
            print(json.loads(res['captions']))
            return
        os.makedirs(OUT, exist_ok=True)
        open(os.path.join(OUT, 'clap_audio.npz'), 'wb').write(res['clap_audio'])
        open(os.path.join(OUT, 'caption_mpnet.npz'), 'wb').write(res['caption_mpnet'])
        open(os.path.join(OUT, 'captions.json'), 'wb').write(res['captions'])
        print('saved to', OUT)
    finally:
        import subprocess
        subprocess.run(['modal', 'volume', 'delete', 'mindread-videos', '--yes'], check=False)
        print('volume mindread-videos delete requested; verify with `modal volume list`')
